type sessionLifetimeHooks struct {
	before func(*runner.Transaction)
}

func (*sessionLifetimeHooks) BeforeAll([]*runner.Transaction) error { return nil }
func (hooks *sessionLifetimeHooks) BeforeEach(transaction *runner.Transaction) error {
	hooks.before(transaction)
	return nil
}
func (*sessionLifetimeHooks) BeforeEachValidation(*runner.Transaction) error { return nil }
func (*sessionLifetimeHooks) AfterEach(*runner.Transaction) error            { return nil }
func (*sessionLifetimeHooks) AfterAll([]*runner.Transaction) error           { return nil }

func TestConfiguredSessionSurvivesAnExpiringBeforeHook(t *testing.T) {
	for _, generated := range []bool{false, true} {
		t.Run(fmt.Sprintf("generated=%t", generated), func(t *testing.T) {
			logins := 0
			var expires time.Time
			var credential string
			loginBody := ""
			const body = `{"message":"unchanged generated bytes","account_id":4}`
			server := httptest.NewServer(http.HandlerFunc(func(response http.ResponseWriter, request *http.Request) {
				contents, err := io.ReadAll(request.Body)
				if err != nil {
					t.Error(err)
					response.WriteHeader(http.StatusInternalServerError)
					return
				}
				if request.URL.Path == "/login" {
					if logins > 0 && string(contents) != loginBody {
						t.Error("renewal changed the configured principal or login body")
					}
					loginBody = string(contents)
					logins++
					credential = fmt.Sprintf("disposable-session-%d", logins)
					expires = time.Now().Add(time.Second)
					response.Header().Set("Content-Type", "application/json")
					fmt.Fprintf(response, `{"token":%q,"expires_in":1}`, credential)
					return
				}
				if request.Header.Get("Authorization") != "Bearer "+credential || !time.Now().Before(expires) {
					response.WriteHeader(http.StatusUnauthorized)
					return
				}
				if string(contents) != body {
					t.Error("renewal changed the generated request body")
					response.WriteHeader(http.StatusBadRequest)
					return
				}
				response.WriteHeader(http.StatusCreated)
			}))
			defer server.Close()
			path := filepath.Join(t.TempDir(), "vertrag.yml")
			settingsText := fmt.Sprintf(`spec: unused.yaml
endpoint: %s
auth:
  login:
    path: /login
    body: {email: owner@example.test, password: disposable-password, client: native}
    secrets: [password]
    public: [email, client]
  carry: bearer
  expires-in: '{$response.body#/expires_in}'
`, server.URL)
			if err := os.WriteFile(path, []byte(settingsText), 0o600); err != nil {
				t.Fatal(err)
			}
			settings, err := config.Load(path)
			if err != nil {
				t.Fatal(err)
			}
			source := compile.Transaction{
				Name:     "send as the configured account",
				Request:  compile.Request{Method: "POST", URI: "/send", Body: body},
				Response: compile.Response{Status: "201"},
			}
			engine := runner.New(server.URL)
			if err := applyConfiguredRules(context.Background(), engine, settings, []compile.Transaction{source}); err != nil {
				t.Fatal(err)
			}
			engine.Hooks = &sessionLifetimeHooks{before: func(*runner.Transaction) { time.Sleep(1100 * time.Millisecond) }}
			var status string
			if generated {
				reply, err := engine.SendGenerated(context.Background(), source)
				if err != nil {
					t.Fatal(err)
				}
				status = reply.StatusCode
			} else {
				reply, err := engine.Send(context.Background(), source)
				if err != nil {
					t.Fatal(err)
				}
				status = reply.StatusCode
			}
			if status != "201" {
				t.Fatalf("configured session expired inside the before hook: got %s, want 201 with the unchanged principal and body", status)
			}
			if logins != 2 || !strings.Contains(loginBody, `"email":"owner@example.test"`) {
				t.Fatalf("login exchanges=%d, want initial login and same-principal renewal", logins)
			}
		})
	}
}

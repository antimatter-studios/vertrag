func TestRenewableCredentialRechecksAfterHooksForEverySendPath(t *testing.T) {
	for _, mode := range []string{"send", "generated", "prepared", "example", "principal", "required-principal"} {
		t.Run(mode, func(t *testing.T) {
			const body = `{"generated":"unchanged","account":4}`
			expired := false
			seen := false
			server := httptest.NewServer(http.HandlerFunc(func(response http.ResponseWriter, request *http.Request) {
				seen = true
				contents, err := io.ReadAll(request.Body)
				if err != nil {
					t.Error(err)
				}
				if string(contents) != body || request.Header.Get("Authorization") != "Bearer renewed-owner" || !expired {
					t.Error("send changed the generated bytes or failed to carry its renewed owner session")
					response.WriteHeader(http.StatusUnauthorized)
					return
				}
				response.WriteHeader(http.StatusCreated)
			}))
			defer server.Close()
			credential := Credential{Header: "Authorization: Bearer initial-owner", Renew: func(context.Context) (string, error) {
				if expired {
					return "Authorization: Bearer renewed-owner", nil
				}
				return "Authorization: Bearer initial-owner", nil
			}}
			engine := New(server.URL)
			engine.Auth = credential
			engine.Hooks = &stubHooks{beforeFn: func(transaction *Transaction) {
				if transaction.Request.Headers["Authorization"] != "Bearer initial-owner" {
					t.Error("before hook did not receive its own initial session")
				}
				expired = true
			}}
			source := compile.Transaction{Name: "protected", Request: compile.Request{Method: "POST", URI: "/send", Body: body}, Response: compile.Response{Status: "201"}}
			switch mode {
			case "send":
				_, err := engine.Send(t.Context(), source)
				if err != nil {
					t.Fatal(err)
				}
			case "generated":
				_, err := engine.SendGenerated(t.Context(), source)
				if err != nil {
					t.Fatal(err)
				}
			case "prepared":
				expired = true
				_, err := engine.Deliver(t.Context(), engine.Prepare(source))
				if err != nil {
					t.Fatal(err)
				}
			case "example":
				result := engine.runOne(t.Context(), engine.Prepare(source))
				if result.Actual.StatusCode != "201" {
					t.Fatalf("example did not send successfully: %v", result.Errors)
				}
			case "principal":
				_, err := engine.SendAs(t.Context(), "owner", source, credential, Carriers{Headers: []string{"Authorization"}})
				if err != nil {
					t.Fatal(err)
				}
			case "required-principal":
				engine.Principals = map[string]Credential{"owner": credential}
				engine.Carriers = Carriers{Headers: []string{"Authorization"}}
				source.Requires = map[string]string{"principal": "owner"}
				result := engine.runOne(t.Context(), engine.Prepare(source))
				if result.Actual.StatusCode != "201" {
					t.Fatalf("required principal did not send successfully: %v", result.Errors)
				}
			}
			if !seen {
				t.Fatal("the request was not sent")
			}
		})
	}
}

func TestRenewalDoesNotRepairAnonymousStaticExcludedOrHookChangedCredentials(t *testing.T) {
	for _, mode := range []string{"anonymous", "static-invalid", "excluded", "login", "hook-changed", "principal-hook-changed"} {
		t.Run(mode, func(t *testing.T) {
			calls := 0
			seen := "not sent"
			server := httptest.NewServer(http.HandlerFunc(func(response http.ResponseWriter, request *http.Request) {
				seen = request.Header.Get("Authorization")
				response.WriteHeader(http.StatusUnauthorized)
			}))
			defer server.Close()
			credential := Credential{Header: "Authorization: Bearer initial", Renew: func(context.Context) (string, error) {
				calls++
				return "Authorization: Bearer renewed", nil
			}}
			engine := New(server.URL)
			engine.Auth = credential
			source := compile.Transaction{Name: "protected", Request: compile.Request{Method: "POST", URI: "/protected"}}
			carriers := Carriers{Headers: []string{"Authorization"}}
			switch mode {
			case "anonymous", "static-invalid":
				principal := Credential{}
				if mode == "static-invalid" {
					principal.Header = "Authorization: Bearer deliberately-invalid"
				}
				if _, err := engine.SendAs(t.Context(), mode, source, principal, carriers); err != nil {
					t.Fatal(err)
				}
			case "excluded":
				engine.Auth.Except = map[string]bool{source.Name: true}
				if _, err := engine.Send(t.Context(), source); err != nil {
					t.Fatal(err)
				}
			case "login":
				engine.Auth.LoginPath, engine.Auth.LoginMethod = "/protected", "POST"
				if _, err := engine.Send(t.Context(), source); err != nil {
					t.Fatal(err)
				}
			case "hook-changed", "principal-hook-changed":
				engine.Hooks = &stubHooks{beforeFn: func(transaction *Transaction) {
					transaction.Request.Headers["Authorization"] = "Bearer deliberately-invalid"
				}}
				if mode == "principal-hook-changed" {
					_, err := engine.SendAs(t.Context(), "owner", source, credential, carriers)
					if !errors.Is(err, ErrCredentialChangedByHook) || seen != "not sent" || calls != 1 {
						t.Fatalf("principal guard was bypassed: calls=%d, sent=%t, error=%v", calls, seen != "not sent", err)
					}
					return
				}
				if _, err := engine.Send(t.Context(), source); err != nil {
					t.Fatal(err)
				}
			}
			want := ""
			if mode == "static-invalid" || mode == "hook-changed" {
				want = "Bearer deliberately-invalid"
			}
			if seen != want {
				t.Fatalf("credential was silently repaired: sent=%q, want=%q", seen, want)
			}
			if mode != "hook-changed" && calls != 0 {
				t.Fatalf("an anonymous/static/excluded credential renewed %d times", calls)
			}
		})
	}
}

func TestRenewalPreservesNonCredentialCookiesAndRejectsCarrierDrift(t *testing.T) {
	for _, changed := range []bool{false, true} {
		t.Run(fmt.Sprint(changed), func(t *testing.T) {
			transaction := trackCredential(newTransaction(compile.Transaction{Name: "cookie", Request: compile.Request{Method: "GET", URI: "/"}}, "http://example.test", []string{"Cookie: session=initial; locale=en"}), Credential{
				Header: "Cookie: session=initial",
				Renew: func(context.Context) (string, error) {
					if changed {
						return "Authorization: Bearer another-carrier", nil
					}
					return "Cookie: session=renewed", nil
				},
			})
			err := transaction.renewCredential(t.Context())
			if changed {
				if err == nil || !strings.Contains(err.Error(), "changed its carrier") {
					t.Fatalf("carrier drift was accepted: %v", err)
				}
				return
			}
			if err != nil || !strings.Contains(transaction.Request.Headers["Cookie"], "locale=en") || !strings.Contains(transaction.Request.Headers["Cookie"], "session=renewed") || strings.Contains(transaction.Request.Headers["Cookie"], "initial") {
				t.Fatalf("cookie renewal lost a non-credential cookie: %v", err)
			}
		})
	}
}
